function riskLevel(title){
  const t = title;
  const high = /低保|争议|处罚|通报|诉讼|纠纷|女|男|疑似|风波|回应|道歉|举报|打假|谣言|曝光/;
  const med  = /芯片|华为|科技|国际|竞争|国产|研发|发布|国产替代|自主/;
  if (high.test(t)) return '高';
  if (med.test(t)) return '中';
  return '低';
}

