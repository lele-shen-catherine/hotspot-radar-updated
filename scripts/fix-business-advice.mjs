const aliasMap = (key) => {
  if (key.includes("旅行")) return "京东旅行";
  if (key.includes("外卖")) return "京东外卖";
  if (key.includes("秒送")) return "京东秒送";
  if (key.includes("家政")) return "京东家政";
  if (key.includes("小厨")) return "七鲜小厨";
  if (key.includes("咖啡")) return "七鲜咖啡";
  if (key.includes("美食")) return "七鲜美食MALL";
  return key;
};

let changed = 0;
for (const t of Object.keys(analyses)) {
  if (t.includes("南方医科大学")) continue;
  const a = analyses[t];
  const plan = plans[t];
  if (!plan) continue;
  (a.business || []).forEach((b) => {
    const key = aliasMap(b.business);
    const v = plan[key];
    if (v === undefined) { b.action = "仅观察不借势"; b.comms = ""; return; }
    b.action = v;
    b.comms = "";
    changed++;
  });
}
fs.writeFileSync("public/data/ai-analysis.json", JSON.stringify(ai, null, 2));
